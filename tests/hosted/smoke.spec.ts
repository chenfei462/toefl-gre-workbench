import { test, expect, type Page } from '@playwright/test'
import { readFile } from 'node:fs/promises'
import { createClient } from '@supabase/supabase-js'
const stateKey = 'toefl-gre-workbench:v2'
const saved = (page: Page) => page.evaluate(key => JSON.parse(localStorage.getItem(key)!), stateKey)
const business = (state: Record<string, unknown>) => { const { _localRevision: revision, ...data } = state; expect(revision).toEqual(expect.any(Number)); return data }
async function login(page: Page) {
  const accounts = JSON.parse(await readFile('.hosted-test-accounts.secret.local', 'utf8'))
  expect(accounts.projectRef).toBe('vcfpdxpprugrgmmilahm')
  const account = accounts.users.find((row: { label: string }) => row.label === 'a')
  await page.getByLabel('邮箱', { exact: true }).fill(account.email)
  await page.getByLabel('密码', { exact: true }).fill(account.password)
  await page.getByRole('button', { name: '登录', exact: true }).click()
  // Clear the UI immediately so a failure snapshot cannot contain a fixture password.
  await page.getByLabel('密码', { exact: true }).fill('')
  await expect(page.getByText('已登录：' + account.email, { exact: true })).toBeVisible()
}

test('hosted Preview supports local-only mobile study, reload and offline shell', async ({ page, context }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/settings')
  await expect(page.getByText('未登录 · 可继续使用本地模式')).toBeVisible()
  await page.getByRole('button', { name: '生成我的 30 天计划' }).click()
  await expect(page.getByRole('heading', { level: 1, name: "Today's Prescription" })).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1)).toBe(true)
  await page.evaluate(async () => { await navigator.serviceWorker.ready })
  await page.reload()
  await expect.poll(() => page.evaluate(() => !!navigator.serviceWorker.controller)).toBe(true)
  await context.setOffline(true)
  await page.reload()
  await expect(page.getByRole('heading', { level: 1, name: "Today's Prescription" })).toBeVisible()
  expect((await saved(page)).tasks.length).toBeGreaterThan(0)
  await context.setOffline(false)
})

test('hosted production UI syncs complete study evidence and private assets to a fresh device', async ({ page, browser }) => {
  const accounts = JSON.parse(await readFile('.hosted-test-accounts.secret.local', 'utf8'))
  const account = accounts.users.find((row: { label: string }) => row.label === 'a')
  const publicEnv = Object.fromEntries((await readFile('.env.hosted.local', 'utf8')).split(/\r?\n/).filter(line => line.startsWith('VITE_')).map(line => { const at = line.indexOf('='); return [line.slice(0, at), line.slice(at + 1)] }))
  const cleanupClient = createClient(publicEnv.VITE_SUPABASE_URL, publicEnv.VITE_SUPABASE_PUBLISHABLE_KEY, { auth: { persistSession: false, autoRefreshToken: false } })
  const signedIn = await cleanupClient.auth.signInWithPassword({ email: account.email, password: account.password })
  expect(signedIn.error).toBeNull()
  expect(signedIn.data.user?.id).toBe(account.id)
  const removed = await cleanupClient.from('workbench_snapshots').delete().eq('user_id', account.id)
  expect(removed.error).toBeNull()
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/')
  await login(page)
  await page.getByRole('button', { name: '生成我的 30 天计划' }).click()
  await page.goto('/questions/import')
  const questions = Array.from({ length: 20 }, (_, index) => ({
    id: 'hosted-' + index, sourceId: 'user-manual', sourceQuestionId: 'hosted-' + index,
    exam: 'gre', examVersion: 'GRE_CURRENT', section: 'verbal', questionType: 'text_completion',
    skillIds: ['gre-text-completion'], prompt: 'User-authored hosted question ' + (index + 1),
    options: [{ id: 'a', text: 'Correct option' }, { id: 'b', text: 'Wrong option' }],
    answer: { optionId: 'a', verification: 'verified' }, answerType: 'single_choice', storageMode: 'full', verification: 'verified',
    compatibility: { examVersion: 'GRE_CURRENT', status: 'current' }, tags: [], explanationIds: [], mediaIds: [],
  }))
  await page.getByLabel('粘贴 JSON / CSV').fill(JSON.stringify({ questions }))
  await page.getByRole('button', { name: '预览导入', exact: true }).click()
  await page.getByRole('dialog').getByRole('button', { name: '确认保存', exact: true }).click()
  await expect(page.getByRole('dialog')).toBeHidden()
  await expect(page.getByText('20 / 20 题', { exact: true })).toBeVisible()
  const bankDownload = page.waitForEvent('download')
  await page.getByRole('button', { name: '导出题库', exact: true }).click()
  const expectedBank = JSON.parse(await readFile((await (await bankDownload).path())!, 'utf8'))
  await page.goto('/practice')
  await expect(page.locator('.practice-picker input[type="checkbox"]')).toHaveCount(20)
  await page.getByRole('button', { name: '选择前 20 题' }).click()
  await page.getByRole('button', { name: '开始练习 · 20 题' }).click()
  for (let index = 0; index < 20; index++) {
    await page.getByLabel(index < 13 ? 'Correct option' : 'Wrong option', { exact: true }).check()
    if (index < 19) await page.getByRole('button', { name: '下一题' }).click()
  }
  await page.getByRole('button', { name: '提交练习', exact: true }).click()
  await page.getByRole('button', { name: '确认提交', exact: true }).click()
  await expect(page.getByText('正确率 65%', { exact: true })).toBeVisible()
  await page.goto('/errors')
  await page.getByRole('button', { name: '开始二刷' }).first().click()
  await page.getByRole('button', { name: '这次答对' }).click()
  await page.goto('/vocabulary')
  for (const [index, word] of ['mitigate', 'lucid', 'tenacious'].entries()) {
    await page.getByLabel('单词', { exact: true }).fill(word)
    await page.getByLabel('词义', { exact: true }).fill('User-defined study meaning')
    await page.getByRole('button', { name: '添加词汇' }).click()
    await page.getByRole('button', { name: '显示词义' }).click()
    await page.getByRole('button', { name: 'Easy', exact: true }).click()
    await expect.poll(async () => (await saved(page)).vocabularyReviews.length).toBe(index + 1)
  }
  await page.goto('/diagnostic')
  await page.getByRole('combobox', { name: '考试', exact: true }).selectOption('gre')
  await page.getByLabel('来源', { exact: true }).fill('Acceptance fixture checkpoint; not actual learner score')
  await page.getByLabel('总分（可留空）').fill('320')
  await page.getByLabel('verbal', { exact: true }).fill('158')
  await page.getByLabel('quant', { exact: true }).fill('162')
  await page.getByRole('button', { name: '保存模考' }).click()
  await expect.poll(async () => (await saved(page)).mockSessions.length).toBe(1)
  await page.goto('/resources')
  await page.getByLabel('材料文件（最多 100 MB，TXT 最多 5 MB）').setInputFiles({ name: 'hosted-notes.txt', mimeType: 'text/plain', buffer: Buffer.from('Private hosted study notes') })
  await page.getByRole('combobox', { name: '材料使用权' }).selectOption('user_owned')
  await page.getByRole('button', { name: '保存材料' }).click()
  await expect(page.getByRole('heading', { name: '本地材料 · 1' })).toBeVisible()
  await page.goto('/speaking')
  await page.getByRole('combobox', { name: '题型', exact: true }).selectOption('interview')
  await page.getByLabel('题目 / 提示').fill('Describe your study routine.')
  await page.getByLabel('准备秒数').fill('0')
  await page.getByRole('button', { name: '开始准备' }).click()
  await expect(page.getByRole('status').filter({ hasText: '正在录音' })).toBeVisible()
  await page.waitForTimeout(1300)
  await page.getByRole('button', { name: '停止录音' }).click()
  await expect(page.getByLabel('复听录音')).toHaveAttribute('src', /^blob:/)
  await expect.poll(async () => (await saved(page)).speakingSessions.length).toBe(1)
  await page.goto('/settings')
  await page.getByRole('button', { name: '立即同步' }).click()
  await expect(page.getByRole('status')).toContainText('已同步')
  const expected = await saved(page)
  expect(expected.errorRecords).toHaveLength(7)
  expect(expected.vocabularyReviews).toHaveLength(3)
  expect(expected.mockSessions).toHaveLength(1)
  expect(expected.speakingSessions).toHaveLength(1)
  const freshContext = await browser.newContext({ storageState: '.vercel/hosted-storage.local' })
  try {
    const fresh = await freshContext.newPage()
    fresh.on('pageerror', error => errors.push(error.message))
    await fresh.goto('/')
    await login(fresh)
    await fresh.getByRole('button', { name: '预览云端备份' }).click()
    await fresh.getByRole('button', { name: '确认使用云端备份' }).click()
    await expect(fresh.getByRole('heading', { level: 1, name: "Today's Prescription" })).toBeVisible()
    const actual = await saved(fresh)
    for (const field of ['profile', 'tasks', 'attempts', 'errorRecords', 'reviewAttempts', 'vocabulary', 'vocabularyReviews', 'mockSessions', 'checkpoints', 'practiceSessions', 'speakingSessions', 'resources', 'weeklyReviews', 'recommendationFeedback', 'userQuestionStates']) {
      await expect.poll(async () => business(await saved(fresh))[field]).toEqual(business(expected)[field])
    }
    expect(actual.questionBank.questions).toHaveLength(20)
    expect(actual.cloudAssets.recordings).toHaveLength(1)
    expect(actual.cloudAssets.materials).toHaveLength(1)
    await fresh.goto('/questions')
    const restoredBankDownload = fresh.waitForEvent('download')
    await fresh.getByRole('button', { name: '导出题库', exact: true }).click()
    const restoredBank = JSON.parse(await readFile((await (await restoredBankDownload).path())!, 'utf8'))
    expect(actual.questionBank).toEqual(expectedBank)
    expect(restoredBank).toEqual(expectedBank)
    await fresh.goto('/resources')
    await fresh.getByText('阅读文本', { exact: true }).click()
    await expect(fresh.getByText('Private hosted study notes', { exact: true })).toBeVisible()
    await fresh.goto('/speaking')
    await fresh.getByLabel('复听录音').evaluate(async element => { await (element as HTMLAudioElement).play() })
    await expect.poll(() => fresh.getByLabel('复听录音').evaluate(element => (element as HTMLAudioElement).currentTime)).toBeGreaterThan(0)
    // A blocked upload leaves downloaded local audio usable.
    await fresh.route('**/storage/v1/object/**', route => route.abort('failed'))
    await fresh.getByRole('button', { name: '设置', exact: true }).click()
    await fresh.getByRole('button', { name: '立即同步' }).click()
    await expect(fresh.getByRole('status')).toContainText('云端操作未完成')
    await fresh.getByRole('button', { name: '口语训练', exact: true }).click()
    await fresh.getByLabel('复听录音').evaluate(async element => { await (element as HTMLAudioElement).play() })
    await expect.poll(() => fresh.getByLabel('复听录音').evaluate(element => (element as HTMLAudioElement).currentTime)).toBeGreaterThan(0)
    await fresh.unroute('**/storage/v1/object/**')
    // A server-side expired-token response cannot prevent saving local settings.
    await fresh.route('**/auth/v1/user', route => route.fulfill({ status: 401, contentType: 'application/json', body: JSON.stringify({ code: 'bad_jwt', message: 'JWT expired' }) }))
    await fresh.getByRole('button', { name: '设置', exact: true }).click()
    await fresh.getByLabel('每天可用时间').fill('70')
    await fresh.getByRole('button', { name: '保存设置', exact: true }).click()
    await expect.poll(async () => (await saved(fresh)).profile.dailyMinutes).toBe(70)
    await fresh.getByRole('button', { name: '立即同步' }).click()
    await expect(fresh.getByRole('status')).toContainText('云端操作未完成')
    expect((await saved(fresh)).errorRecords).toHaveLength(7)
    await fresh.unroute('**/auth/v1/user')
    // Both devices share one base; the second writer must expose a conflict.
    await fresh.getByRole('button', { name: '立即同步' }).click()
    await expect(fresh.getByRole('status')).toContainText('已同步')
    await page.getByLabel('每天可用时间').fill('90')
    await page.getByRole('button', { name: '保存设置', exact: true }).click()
    await expect.poll(async () => (await saved(page)).profile.dailyMinutes).toBe(90)
    await page.getByRole('button', { name: '立即同步' }).click()
    await expect(page.getByRole('alert')).toContainText('同步冲突')
    await page.getByRole('button', { name: '使用云端：先预览' }).click()
    await page.getByRole('button', { name: '确认使用云端备份' }).click()
    await expect(page.getByLabel('每天可用时间')).toHaveValue('70')
  } finally { await freshContext.close() }
  expect(errors).toEqual([])
})
