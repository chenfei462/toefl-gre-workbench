import { test, expect } from '@playwright/test'

test('reset followed by onboarding saves the new plan durably', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: '生成我的 30 天计划' }).click()
  await page.getByRole('button', { name: '设置', exact: true }).click()
  page.on('dialog', dialog => dialog.accept())
  await page.getByRole('button', { name: /清空所有数据/ }).click()
  await page.getByLabel('每天可用时间').fill('45')
  await page.getByRole('button', { name: '生成我的 30 天计划' }).click()
  await expect.poll(() => page.evaluate(() => JSON.parse(localStorage.getItem('toefl-gre-workbench:v2') ?? '{}').profile?.dailyMinutes)).toBe(45)
  await page.reload()
  await expect(page.getByRole('heading', { level: 1, name: "Today's Prescription" })).toBeVisible()
})

test('stale tab cannot replace another tab’s saved preferences', async ({ page, context }) => {
  await page.goto('/')
  await page.getByRole('button', { name: '生成我的 30 天计划' }).click()
  await expect.poll(() => page.evaluate(() => JSON.parse(localStorage.getItem('toefl-gre-workbench:v2') ?? '{}').tasks?.length ?? 0)).toBeGreaterThan(0)
  await page.goto('/settings')
  const other = await context.newPage()
  await other.goto('/settings')
  await page.getByLabel('每天可用时间').fill('90')
  await page.getByRole('button', { name: '保存设置', exact: true }).click()
  await expect.poll(() => page.evaluate(() => JSON.parse(localStorage.getItem('toefl-gre-workbench:v2')!).profile.dailyMinutes)).toBe(90)
  await other.getByLabel('每天可用时间').fill('30')
  await other.getByRole('button', { name: '保存设置', exact: true }).click()
  await expect(other.getByRole('alert')).toContainText('another tab')
  expect(await other.evaluate(() => JSON.parse(localStorage.getItem('toefl-gre-workbench:v2')!).profile.dailyMinutes)).toBe(90)
  await expect(other.getByRole('button', { name: '导出当前数据' })).toBeVisible()
})

